// scripts/generate-image-list.mjs
//
// Scans public/images/side-project and writes lib/side-projects.ts
// containing a typed array of image paths — avoids hand-typing filenames
// that contain spaces, apostrophes, and ampersands.
//
// Usage:
//   node scripts/generate-image-list.mjs

import { readdir } from "fs/promises";
import { writeFile } from "fs/promises";
import { join } from "path";

const SOURCE_DIR = "public/images/side-project";
const OUTPUT_FILE = "lib/side-projects.ts";

async function main() {
  const entries = await readdir(SOURCE_DIR, { withFileTypes: true });

  const images = entries
    .filter((e) => e.isFile() && e.name.toLowerCase().endsWith(".webp"))
    .map((e) => `/images/side-project/${e.name}`)
    .sort((a, b) => a.localeCompare(b));

  if (images.length === 0) {
    console.error(`No .webp files found in ${SOURCE_DIR}`);
    process.exit(1);
  }

  const fileContents = `// Auto-generated by scripts/generate-image-list.mjs
// Re-run that script any time you add/remove images from
// public/images/side-project to keep this list in sync.

export const sideProjectImages: string[] = [
${images.map((src) => `  "${src}",`).join("\n")}
];
`;

  await writeFile(OUTPUT_FILE, fileContents, "utf-8");

  console.log(`✔ Wrote ${images.length} image paths to ${OUTPUT_FILE}`);
}

main().catch((err) => {
  console.error("Failed to generate image list:", err.message);
  process.exit(1);
});